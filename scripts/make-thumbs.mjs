// npm run thumbs: for every public/art/cover-<category>-<n>.webp make a small tile thumbnail
// (public/art/thumbs/cover-<category>-<n>.webp, 240x427) and rewrite src/demos/coverArt.ts so the app knows
// which designs have art. Run it after adding cover art; `npm run build` runs it first (prebuild).
import { readdir, writeFile, mkdir, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const art = path.join(root, 'public/art');
const out = path.join(art, 'thumbs');
await mkdir(out, { recursive: true });

const covers = (await readdir(art)).filter((f) => /^cover-[a-z]+-\d+\.webp$/.test(f)).sort((a, b) => {
  const [ca, na] = [a.split('-')[1], Number(a.split('-')[2].replace('.webp', ''))];
  const [cb, nb] = [b.split('-')[1], Number(b.split('-')[2].replace('.webp', ''))];
  return ca === cb ? na - nb : ca.localeCompare(cb);
});

let made = 0;
for (const f of covers) {
  const src = path.join(art, f);
  const dst = path.join(out, f);
  let fresh = false;
  try { fresh = (await stat(dst)).mtimeMs >= (await stat(src)).mtimeMs; } catch { /* missing */ }
  if (fresh) continue;
  await sharp(src).resize(240, 427, { fit: 'cover', position: 'centre' }).webp({ quality: 58, effort: 5 }).toFile(dst);
  made++;
}

const keys = covers.map((f) => f.slice(6, -5));
const list = keys.map((k) => `'${k}'`).join(', ');
await writeFile(path.join(root, 'src/demos/coverArt.ts'),
`/* GENERATED by scripts/make-thumbs.mjs (npm run thumbs): designs that have cover art in public/art/cover-<category>-<n>.webp.
   Known synchronously so a cover paints its art from the first frame, and so a design is listed only when its art exists. */
export const COVER_ART: ReadonlySet<string> = new Set([
  ${list}
]);
`);
console.log(`thumbs: ${covers.length} covers, ${made} thumbnail(s) made`);
